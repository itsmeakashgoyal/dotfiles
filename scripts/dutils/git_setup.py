#
#  ▓▓▓▓▓▓▓▓▓▓
# ░▓ author ▓ Akash Goyal
# ░▓ file   ▓ scripts/dutils/git_setup.py
# ░▓▓▓▓▓▓▓▓▓▓
#
# Git identities + SSH keys for any number of accounts (personal, one or more
# companies), on macOS, Linux and Windows. See docs/SSH.md.
#
# Everything machine-specific lives OUTSIDE the repo, in ~/.config/dotfiles/git/:
#   profiles.json        the source of truth (written by this command)
#   config               generated; included by the tracked git/.config/git/config
#   <profile>.gitconfig  generated; user.name/email, SSH key, optional signing
# plus ~/.ssh/config.d/dotfiles (generated Host blocks, Included from ~/.ssh/config).
#
# How a repo picks its identity (no special URLs to remember):
#   1. The machine DEFAULT profile applies everywhere.
#   2. A profile also applies when the repo is under one of its folders
#      (e.g. ~/work/), or its remote belongs to one of its GitHub orgs
#      (git@github.com:acme/…, https://github.com/acme/…) or enterprise hosts
#      (github.acme.com), or uses its SSH alias (git@github-acme:…).
#   3. SSH URLs for a profile's orgs are rewritten to its alias, so clones and
#      pushes use the right key automatically; core.sshCommand pins the key for
#      every repo that resolved to the profile.
#
# Usage:
#   dutils git-setup                 interactive wizard (first run, or to edit)
#   dutils git-setup status [PATH]   profiles + which identity PATH (cwd) gets
#   dutils git-setup add NAME [...]  add/update a profile (flags or prompts)
#   dutils git-setup remove NAME
#   dutils git-setup default NAME
#   dutils git-setup apply           regenerate git + ssh config from profiles.json
#   dutils git-setup migrate         import the old config-local/github-private setup
#   dutils git-setup test            ssh -T against every profile's alias/host

import argparse
import json
import os
import platform
import re
import shutil
import stat
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "lib"))
from dutil import ok, info, step, warn, fail, section, confirm  # noqa: E402

IS_WINDOWS = platform.system() == "Windows"
IS_MAC = platform.system() == "Darwin"
HOME = Path.home()
REPO = Path(__file__).resolve().parent.parent.parent

STATE_DIR = HOME / ".config" / "dotfiles" / "git"
PROFILES_JSON = STATE_DIR / "profiles.json"
GIT_INCLUDE = STATE_DIR / "config"
SSH_DIR = HOME / ".ssh"
SSH_CONFIG = SSH_DIR / "config"
SSH_INCLUDE = SSH_DIR / "config.d" / "dotfiles"
SSH_INCLUDE_LINE = "Include ~/.ssh/config.d/dotfiles"

# Legacy (pre-profiles) files, only read by `migrate`.
LEGACY_LOCAL = HOME / ".config" / "git" / "config-local"
LEGACY_PERSONAL = HOME / ".config" / "git" / "config-personal"
_LEGACY_BLOCK = re.compile(r"# >>> dutils ssh-setup: (\S+) >>>.*?# <<< dutils ssh-setup: \1 <<<\n?", re.S)

HEADER = "Generated by `dutils git-setup` from ~/.config/dotfiles/git/profiles.json — don't edit by hand."
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9_-]*$")


# ══════════════════════════════════════════════════════════════════════════════
# profiles.json
# ══════════════════════════════════════════════════════════════════════════════
def load() -> dict:
    if PROFILES_JSON.exists():
        data = json.loads(PROFILES_JSON.read_text())
        data.setdefault("profiles", {})
        return data
    return {"version": 1, "default": None, "profiles": {}}


def save(data: dict) -> None:
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    PROFILES_JSON.write_text(json.dumps(data, indent=2) + "\n")
    _private(PROFILES_JSON)


def _private(path: Path) -> None:
    if not IS_WINDOWS:
        os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)


def _tilde(path: str | Path) -> str:
    """~-relative form, so generated files read the same on every machine."""
    p = str(Path(str(path)).expanduser())
    home = str(HOME)
    return "~" + p[len(home):].replace("\\", "/") if p.startswith(home) else p


def _dir(d: str) -> str:
    d = _tilde(d.strip())
    return d if d.endswith("/") else d + "/"


def _split(value: str | list | None) -> list[str]:
    if not value:
        return []
    items = value if isinstance(value, list) else re.split(r"[,\s]+", value)
    return [i.strip() for i in items if i and i.strip()]


# ══════════════════════════════════════════════════════════════════════════════
# rendering
# ══════════════════════════════════════════════════════════════════════════════
def _match_patterns(p: dict, kind: str) -> list[str]:
    """includeIf conditions that select profile `p`: kind "dir" or "remote"."""
    if kind == "dir":
        return [f"gitdir:{d}" for d in p.get("dirs", [])]
    conds: list[str] = []
    for org in p.get("orgs", []):
        for o in dict.fromkeys([org, org.lower()]):
            conds += [f"hasconfig:remote.*.url:git@github.com:{o}/**",
                      f"hasconfig:remote.*.url:https://github.com/{o}/**",
                      f"hasconfig:remote.*.url:ssh://git@github.com/{o}/**"]
    for host in p.get("hosts", []):
        conds += [f"hasconfig:remote.*.url:git@{host}:*/**",
                  f"hasconfig:remote.*.url:https://{host}/**",
                  f"hasconfig:remote.*.url:ssh://git@{host}/**"]
    for alias in p.get("aliases", []):
        conds.append(f"hasconfig:remote.*.url:git@{alias}:*/**")
    return conds


def render_git(data: dict) -> dict[Path, str]:
    files: dict[Path, str] = {}
    default = data.get("default")
    lines = [f"# {HEADER}", "",
             "# Precedence (later wins): default < folder rules < remote rules, so",
             "# e.g. a personal repo cloned inside ~/work/ still commits as personal.", ""]
    if default in data["profiles"]:
        lines += [f"# Default identity on this machine: {default}", "[include]",
                  f"\tpath = {default}.gitconfig", ""]
    lines.append("# ── folder rules " + "─" * 50)
    for name, p in data["profiles"].items():
        for cond in _match_patterns(p, "dir"):
            lines += [f'[includeIf "{cond}"]', f"\tpath = {name}.gitconfig"]
    lines.append("")
    for name, p in data["profiles"].items():
        lines.append(f"# ── remote rules: {name} " + "─" * max(4, 48 - len(name)))
        for cond in _match_patterns(p, "remote"):
            lines += [f'[includeIf "{cond}"]', f"\tpath = {name}.gitconfig"]
        # Non-default profiles: send their orgs' SSH URLs through their own key.
        aliases = p.get("aliases", [])
        if name != default and aliases and p.get("orgs"):
            for org in p["orgs"]:
                lines += [f'[url "git@{aliases[0]}:{org}/"]',
                          f"\tinsteadOf = git@github.com:{org}/",
                          f"\tinsteadOf = ssh://git@github.com/{org}/"]
        lines.append("")
    files[GIT_INCLUDE] = "\n".join(lines)

    # Lets `git log --show-signature` verify commits signed by any of our keys.
    signers = []
    for p in data["profiles"].values():
        pub = Path(str(Path(p.get("key", "")).expanduser()) + ".pub")
        if p.get("sign") and p.get("key") and pub.exists():
            signers.append(f'{p["email"]} namespaces="git" {pub.read_text().strip()}')
    if signers:
        files[STATE_DIR / "allowed_signers"] = "\n".join(signers) + "\n"
        files[GIT_INCLUDE] += ('[gpg "ssh"]\n'
                               f"\tallowedSignersFile = {_tilde(STATE_DIR / 'allowed_signers')}\n")
    for name, p in data["profiles"].items():
        key = p.get("key", "")
        body = [f"# {HEADER}", f"# Profile: {name}", "[user]",
                f"\tname = {p['name']}", f"\temail = {p['email']}"]
        if p.get("sign") and key:
            body += [f"\tsigningkey = {key}.pub", "[gpg]", "\tformat = ssh",
                     "[commit]", "\tgpgSign = true", "[tag]", "\tgpgSign = true"]
        if key:
            body += ["[core]", f"\tsshCommand = ssh -i {key} -o IdentitiesOnly=yes"]
        files[STATE_DIR / f"{name}.gitconfig"] = "\n".join(body) + "\n"
    return files


def _ssh_block(patterns: list[str], key: str, hostname: str | None) -> list[str]:
    block = [f"Host {' '.join(patterns)}"]
    if hostname:
        block.append(f"    HostName {hostname}")
    block += ["    User git", f"    IdentityFile {key}", "    IdentitiesOnly yes", "    AddKeysToAgent yes"]
    if IS_MAC:
        block.append("    UseKeychain yes")
    return block + [""]


def render_ssh(data: dict) -> str:
    lines = [f"# {HEADER}", ""]
    if IS_MAC:
        lines += ["IgnoreUnknown UseKeychain", ""]
    default = data.get("default")
    for name, p in data["profiles"].items():
        key = p.get("key")
        if not key:
            continue
        if p.get("aliases"):
            lines += [f"# {name}"] + _ssh_block(p["aliases"], key, "github.com")
        for host in p.get("hosts", []):
            lines += [f"# {name} (enterprise)"] + _ssh_block([host], key, None)
    if default in data["profiles"] and data["profiles"][default].get("key"):
        lines += [f"# Plain github.com uses the default profile ({default})"]
        lines += _ssh_block(["github.com"], data["profiles"][default]["key"], None)
    return "\n".join(lines)


def ensure_ssh_include() -> None:
    """`Include` must come before any Host block in ~/.ssh/config to apply."""
    SSH_DIR.mkdir(parents=True, exist_ok=True)
    if not IS_WINDOWS:
        os.chmod(SSH_DIR, stat.S_IRWXU)
    text = SSH_CONFIG.read_text() if SSH_CONFIG.exists() else ""
    text = _LEGACY_BLOCK.sub("", text)  # blocks written by the old `dutils ssh-setup`
    if SSH_INCLUDE_LINE not in text:
        text = (f"# Identities managed by `dutils git-setup` (keep this first)\n"
                f"{SSH_INCLUDE_LINE}\n\n" + text.lstrip("\n"))
    SSH_CONFIG.write_text(text)
    _private(SSH_CONFIG)


def apply(data: dict) -> None:
    if not data["profiles"]:
        warn("No profiles yet — run `dutils git-setup` first.")
        return
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    keep = {GIT_INCLUDE, PROFILES_JSON}
    for path, content in render_git(data).items():
        path.write_text(content)
        keep.add(path)
    for stale in [*STATE_DIR.glob("*.gitconfig"), STATE_DIR / "allowed_signers"]:
        if stale not in keep and stale.exists():
            stale.unlink()
    SSH_INCLUDE.parent.mkdir(parents=True, exist_ok=True)
    SSH_INCLUDE.write_text(render_ssh(data))
    _private(SSH_INCLUDE)
    ensure_ssh_include()
    ok(f"Wrote git config → {_tilde(STATE_DIR)}/  ·  ssh config → {_tilde(SSH_INCLUDE)}")


# ══════════════════════════════════════════════════════════════════════════════
# SSH keys
# ══════════════════════════════════════════════════════════════════════════════
def _existing_keys() -> list[Path]:
    return sorted(p.with_suffix("") for p in SSH_DIR.glob("*.pub") if p.with_suffix("").exists())


def generate_key(path: Path, email: str, no_passphrase: bool) -> None:
    if shutil.which("ssh-keygen") is None:
        fail("ssh-keygen not found (install OpenSSH) — can't create a key.")
        sys.exit(1)
    SSH_DIR.mkdir(parents=True, exist_ok=True)
    step(f"Generating ed25519 key {_tilde(path)}")
    cmd = ["ssh-keygen", "-t", "ed25519", "-C", email, "-f", str(path)]
    if no_passphrase:
        cmd += ["-N", ""]
    subprocess.run(cmd, check=True)
    _private(path)
    if IS_MAC:
        subprocess.run(["ssh-add", "--apple-use-keychain", str(path)], stderr=subprocess.DEVNULL)


def choose_key(name: str, email: str, current: str | None, yes: bool) -> str:
    suggested = SSH_DIR / f"id_ed25519_{name}"
    if yes:
        if current:
            return current
        if not suggested.exists():
            generate_key(suggested, email, no_passphrase=True)
        return _tilde(suggested)
    keys = _existing_keys()
    print(f"\n  SSH key for '{name}':")
    for i, k in enumerate(keys, 1):
        mark = "  (current)" if current and _tilde(k) == current else ""
        print(f"    {i}) {_tilde(k)}{mark}")
    print(f"    n) generate a new key ({_tilde(suggested)})")
    default = next((str(i) for i, k in enumerate(keys, 1) if current and _tilde(k) == current), "n")
    choice = input(f"  Choose [{default}]: ").strip() or default
    if choice.isdigit() and 1 <= int(choice) <= len(keys):
        return _tilde(keys[int(choice) - 1])
    path = suggested
    n = 2
    while path.exists():
        path = SSH_DIR / f"id_ed25519_{name}_{n}"
        n += 1
    generate_key(path, email, no_passphrase=False)
    return _tilde(path)


def show_public_key(key: str) -> None:
    pub = Path(str(Path(key).expanduser()) + ".pub")
    if not pub.exists():
        return
    text = pub.read_text().strip()
    print(f"\n  {text}")
    for cmd in (["pbcopy"], ["clip"], ["wl-copy"], ["xclip", "-selection", "clipboard"]):
        if shutil.which(cmd[0]):
            subprocess.run(cmd, input=text.encode(), check=False)
            info("Copied to the clipboard — add it at https://github.com/settings/keys "
                 "(as an Authentication key, and a Signing key if signing is on)")
            break


# ══════════════════════════════════════════════════════════════════════════════
# interactive bits
# ══════════════════════════════════════════════════════════════════════════════
def ask(prompt: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    return input(f"  {prompt}{suffix}: ").strip() or default


def _guess_name() -> str:
    for p in load()["profiles"].values():
        if p.get("name"):
            return p["name"]
    try:
        import pwd
        return pwd.getpwuid(os.getuid()).pw_gecos.split(",")[0]  # type: ignore[attr-defined]
    except (ImportError, KeyError, AttributeError):
        return os.environ.get("USERNAME", "")


def edit_profile(data: dict, name: str, args: argparse.Namespace | None = None, yes: bool = False) -> None:
    a = args or argparse.Namespace()
    cur = data["profiles"].get(name, {})
    personal = name == "personal"
    interactive = not yes

    def val(attr: str, prompt: str, default: str) -> str:
        given = getattr(a, attr, None)
        if given:
            return given
        return ask(prompt, default) if interactive else default

    section(f"Profile: {name}")
    p = dict(cur)
    p["name"] = val("name", "Git author name", cur.get("name") or _guess_name())
    p["email"] = val("email", "Email", cur.get("email", ""))
    if not p["email"]:
        fail("An email is required.")
        sys.exit(1)

    org_hint = "Your GitHub username(s)" if personal else "Company GitHub org(s) on github.com"
    orgs = getattr(a, "org", None) or _split(val("orgs_str", f"{org_hint}, comma-separated (optional)",
                                                 ",".join(cur.get("orgs", []))))
    p["orgs"] = _split(orgs)
    if not personal:
        hosts = getattr(a, "host", None) or _split(val("hosts_str", "GitHub Enterprise host(s), e.g. "
                                                       "github.acme.com (optional)", ",".join(cur.get("hosts", []))))
        p["hosts"] = _split(hosts)
    else:
        p["hosts"] = _split(getattr(a, "host", None) or cur.get("hosts", []))
    default_dir = "~/personal/" if personal else "~/work/"
    dirs = getattr(a, "dir", None) or _split(val("dirs_str", "Folder(s) whose repos always use this identity",
                                                 ",".join(cur.get("dirs", [default_dir]))))
    p["dirs"] = [_dir(d) for d in _split(dirs)]

    aliases = cur.get("aliases") or [f"github-{name}"]
    p["aliases"] = list(dict.fromkeys(aliases))
    key = getattr(a, "key", None)
    p["key"] = _tilde(key) if key else choose_key(name, p["email"], cur.get("key"), yes)
    if getattr(a, "sign", None) is not None:
        p["sign"] = a.sign
    elif interactive:
        p["sign"] = confirm(f"Sign commits with {p['key']} (SSH signing, shows 'Verified' on GitHub)?")
    else:
        p["sign"] = cur.get("sign", False)

    data["profiles"][name] = p
    if not data.get("default") or getattr(a, "make_default", False):
        data["default"] = name
    if interactive or p["key"] != cur.get("key"):
        show_public_key(p["key"])


def pick_default(data: dict) -> None:
    names = list(data["profiles"])
    if len(names) < 2:
        data["default"] = names[0] if names else None
        return
    print("\n  Which identity should be this machine's DEFAULT (repos that match no rule)?")
    for i, n in enumerate(names, 1):
        print(f"    {i}) {n}  <{data['profiles'][n]['email']}>")
    cur = names.index(data["default"]) + 1 if data.get("default") in names else 1
    choice = ask("Choose", str(cur))
    if choice.isdigit() and 1 <= int(choice) <= len(names):
        data["default"] = names[int(choice) - 1]


def wizard(yes: bool) -> None:
    data = load()
    if not data["profiles"] and (LEGACY_LOCAL.exists() or LEGACY_PERSONAL.exists()):
        info("Found the old config-local / config-personal setup.")
        if yes or confirm("Import it as profiles (recommended)?"):
            migrate(yes=True)
            data = load()

    if not data["profiles"]:
        section("Git identities — first run")
        info("Personal first; then add as many work/company profiles as you need.")
        edit_profile(data, "personal", yes=yes)
        while not yes and confirm("Add a work/company profile?"):
            name = ask("Short profile name (e.g. the company: acme)").lower()
            if not NAME_RE.match(name):
                warn("Use lowercase letters, digits, - or _.")
                continue
            edit_profile(data, name)
        if not yes:
            pick_default(data)
    else:
        status(data)
        while True:
            print("\n  a) add/edit a profile   d) change default   r) remove a profile   q) save & quit")
            choice = ask("Choose", "q").lower()
            if choice == "a":
                name = ask("Profile name (personal, or a company name)").lower()
                if NAME_RE.match(name):
                    edit_profile(data, name)
                else:
                    warn("Use lowercase letters, digits, - or _.")
            elif choice == "d":
                pick_default(data)
            elif choice == "r":
                name = ask("Profile to remove").lower()
                if data["profiles"].pop(name, None) is not None and data.get("default") == name:
                    data["default"] = next(iter(data["profiles"]), None)
            else:
                break

    save(data)
    apply(data)
    offer_dotfiles_remote()
    section("Next")
    info("Add each new public key to the matching GitHub account, then: dutils git-setup test")


def offer_dotfiles_remote() -> None:
    """A bootstrap clone uses HTTPS (no key needed yet); offer to switch to SSH."""
    try:
        url = subprocess.run(["git", "-C", str(REPO), "remote", "get-url", "origin"],
                             capture_output=True, text=True).stdout.strip()
    except OSError:
        return
    m = re.match(r"https://github\.com/([^/]+)/([^/]+?)(?:\.git)?/?$", url)
    if not m:
        return
    ssh_url = f"git@github.com:{m.group(1)}/{m.group(2)}.git"
    if confirm(f"Switch this dotfiles repo's remote to SSH ({ssh_url})?"):
        subprocess.run(["git", "-C", str(REPO), "remote", "set-url", "origin", ssh_url], check=False)
        ok("Remote switched")


# ══════════════════════════════════════════════════════════════════════════════
# status / test / migrate
# ══════════════════════════════════════════════════════════════════════════════
def _git_get(key: str, cwd: Path, file: Path | None = None) -> str:
    cmd = ["git", "config"] + (["-f", str(file)] if file else []) + ["--get", key]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=str(cwd))
    return r.stdout.strip()


def status(data: dict | None = None, path: Path | None = None) -> None:
    data = data or load()
    section("Git identities")
    if not data["profiles"]:
        warn("None configured — git will refuse to commit. Run: dutils git-setup")
        return
    for name, p in data["profiles"].items():
        mark = "  ★ default" if name == data.get("default") else ""
        print(f"  {name:<10} {p['name']} <{p['email']}>{mark}")
        rules = [*(f"dir {d}" for d in p.get("dirs", [])), *(f"org {o}" for o in p.get("orgs", [])),
                 *(f"host {h}" for h in p.get("hosts", [])), *(f"alias {a}" for a in p.get("aliases", []))]
        print(f"  {'':<10} key {p.get('key', '—')}{'  (signing)' if p.get('sign') else ''}")
        if rules:
            print(f"  {'':<10} when: {', '.join(rules)}")
    target = (path or Path.cwd()).resolve()
    inside = subprocess.run(["git", "-C", str(target), "rev-parse", "--is-inside-work-tree"],
                            capture_output=True, text=True).stdout.strip() == "true"
    if inside:
        email = _git_get("user.email", target) or "(none!)"
        print(f"\n  {_tilde(target)} commits as: {email}")


def test(data: dict) -> None:
    section("SSH test")
    for name, p in data["profiles"].items():
        for host in [*(p.get("aliases", [])[:1]), *p.get("hosts", [])]:
            r = subprocess.run(["ssh", "-T", "-o", "BatchMode=yes", "-o", "ConnectTimeout=8",
                                f"git@{host}"], capture_output=True, text=True)
            out = (r.stdout + r.stderr).strip().splitlines()
            msg = next((line for line in out if "successfully authenticated" in line), "")
            if msg:
                ok(f"{name:<10} {host}: {msg.split('!')[0]}")
            else:
                warn(f"{name:<10} {host}: {out[-1] if out else 'no response'}")


def migrate(yes: bool = False) -> None:
    """Import the old setup: tracked gmail default + config-local work override +
    the `github-private` SSH alias."""
    data = load()
    if data["profiles"] and not yes and not confirm("Profiles already exist — merge the old setup in?"):
        return
    ssh_text = SSH_CONFIG.read_text() if SSH_CONFIG.exists() else ""
    m = re.search(r"Host github-private\b.*?IdentityFile\s+(\S+)", ssh_text, re.S)
    personal_key = m.group(1) if m else ""
    if LEGACY_PERSONAL.exists():
        owner = re.search(r"[:/]([^/:]+)/[^/]+?(?:\.git)?$",
                          subprocess.run(["git", "-C", str(REPO), "remote", "get-url", "origin"],
                                         capture_output=True, text=True).stdout.strip())
        data["profiles"]["personal"] = {
            "name": _git_get("user.name", HOME, LEGACY_PERSONAL),
            "email": _git_get("user.email", HOME, LEGACY_PERSONAL),
            "orgs": [owner.group(1)] if owner else [], "hosts": [], "dirs": ["~/personal/"],
            "aliases": ["github-personal", "github-private"], "key": personal_key, "sign": False,
        }
    if LEGACY_LOCAL.exists():
        work_key = SSH_DIR / "id_ed25519"
        data["profiles"]["work"] = {
            "name": _git_get("user.name", HOME, LEGACY_LOCAL),
            "email": _git_get("user.email", HOME, LEGACY_LOCAL),
            "orgs": [], "hosts": [], "dirs": ["~/work/"], "aliases": ["github-work"],
            "key": _tilde(work_key) if work_key.exists() else "", "sign": False,
        }
        data["default"] = "work"
    elif "personal" in data["profiles"]:
        data["default"] = data.get("default") or "personal"
    if not data["profiles"]:
        warn("Nothing to migrate.")
        return
    save(data)
    apply(data)
    ok("Imported: " + ", ".join(f"{n} <{p['email']}>" for n, p in data["profiles"].items())
       + f"; default = {data['default']}")
    info("Add your company's GitHub orgs/hosts so work repos are detected automatically: "
         "dutils git-setup add work")
    info(f"The old {LEGACY_LOCAL.name} / {LEGACY_PERSONAL.name} files are no longer read; delete them when happy.")


# ══════════════════════════════════════════════════════════════════════════════
def main() -> None:
    parser = argparse.ArgumentParser(prog="dutils git-setup",
                                     description="Git identities + SSH keys for personal and work accounts.")
    parser.add_argument("-y", "--yes", action="store_true", help="Accept defaults; no prompts where possible.")
    sub = parser.add_subparsers(dest="cmd")
    p_status = sub.add_parser("status", help="Show profiles and which identity a repo gets.")
    p_status.add_argument("path", nargs="?", type=Path)
    p_add = sub.add_parser("add", help="Add or update a profile.")
    p_add.add_argument("profile", help="personal, or a short company name (e.g. acme)")
    p_add.add_argument("--name", help="Git author name")
    p_add.add_argument("--email")
    p_add.add_argument("--org", action="append", help="GitHub org/user on github.com (repeatable)")
    p_add.add_argument("--host", action="append", help="GitHub Enterprise host (repeatable)")
    p_add.add_argument("--dir", action="append", help="Folder whose repos use this profile (repeatable)")
    p_add.add_argument("--key", help="Existing private key path (default: pick or generate)")
    p_add.add_argument("--sign", action=argparse.BooleanOptionalAction, default=None,
                       help="SSH-sign commits and tags")
    p_add.add_argument("--default", dest="make_default", action="store_true", help="Make it the machine default")
    p_rm = sub.add_parser("remove", help="Remove a profile.")
    p_rm.add_argument("profile")
    p_def = sub.add_parser("default", help="Set the machine-default profile.")
    p_def.add_argument("profile")
    sub.add_parser("apply", help="Regenerate git + ssh config from profiles.json.")
    sub.add_parser("migrate", help="Import the old config-local / github-private setup.")
    sub.add_parser("test", help="ssh -T against every profile.")
    argv = sys.argv[1:]
    yes = any(a in ("-y", "--yes") for a in argv)  # accepted before or after the subcommand
    args = parser.parse_args([a for a in argv if a not in ("-y", "--yes")])
    args.yes = yes

    if args.cmd is None:        wizard(args.yes)
    elif args.cmd == "status":
        status(path=args.path)
    elif args.cmd == "add":
        if not NAME_RE.match(args.profile):
            fail("Profile names: lowercase letters, digits, - or _.")
            sys.exit(1)
        data = load()
        edit_profile(data, args.profile, args, yes=args.yes)
        save(data)
        apply(data)
    elif args.cmd == "remove":
        data = load()
        if data["profiles"].pop(args.profile, None) is None:
            fail(f"No profile '{args.profile}'.")
            sys.exit(1)
        if data.get("default") == args.profile:
            data["default"] = next(iter(data["profiles"]), None)
        save(data)
        apply(data)
    elif args.cmd == "default":
        data = load()
        if args.profile not in data["profiles"]:
            fail(f"No profile '{args.profile}'.")
            sys.exit(1)
        data["default"] = args.profile
        save(data)
        apply(data)
    elif args.cmd == "apply":
        apply(load())
    elif args.cmd == "migrate":
        migrate(args.yes)
    elif args.cmd == "test":
        test(load())


if __name__ == "__main__":
    main()
